export function normalizeLocale(value) {
  const locale = String(value || '').trim().toLowerCase();
  if (locale === 'zh' || locale.startsWith('zh-')) return 'zh-CN';
  if (locale === 'en' || locale.startsWith('en-')) return 'en';
  return null;
}

export function resolveLocale({ stored, languages = [] } = {}) {
  const saved = normalizeLocale(stored);
  if (saved) return saved;
  for (const language of languages || []) {
    const normalized = normalizeLocale(language);
    if (normalized) return normalized;
  }
  return DEFAULT_LOCALE;
}

export function translate(locale, key, params = {}) {
  const normalized = normalizeLocale(locale) || DEFAULT_LOCALE;
  const value = messages[normalized]?.[key] ?? messages[DEFAULT_LOCALE]?.[key];
  if (typeof value === 'function') return value(params);
  if (typeof value !== 'string') return key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

export function catalogKeys(locale) {
  return Object.keys(messages[normalizeLocale(locale) || DEFAULT_LOCALE]).sort();
}
