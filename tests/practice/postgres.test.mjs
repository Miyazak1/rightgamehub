import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import pg from '../../apps/api/node_modules/pg/lib/index.js';
import Fastify from '../../apps/api/node_modules/fastify/fastify.js';
import { PostgresPracticeRepository } from '../../apps/api/src/practice/repository.mjs';
import { createPracticeService, createPracticeWorker } from '../../apps/api/src/practice/service.mjs';
import { createVerifiedMathEngine } from '../../apps/api/src/practice/engine.mjs';
import { registerPracticeRoutes } from '../../apps/api/src/practice/routes.mjs';
import { PracticeError } from '../../apps/api/src/practice/error.mjs';

const url = process.env.PRACTICE_TEST_DATABASE_URL;
test('PostgreSQL + actual frozen worker: lifecycle, recovery, confidentiality, concurrency and non-repetition', { skip: !url, timeout: 240000 }, async t => {
  const parsed = new URL(url);
  assert.ok(['127.0.0.1', 'localhost'].includes(parsed.hostname) && parsed.pathname === '/mooyu_practice_acceptance', 'Only the dedicated loopback acceptance database is allowed');
  const schema = 'practice_test_' + randomUUID().replaceAll('-', '');
  const admin = new pg.Pool({ connectionString: url });
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool = new pg.Pool({ connectionString: url, options: `-c search_path=${schema},public` });
  const app = Fastify({ ajv: { customOptions: { removeAdditional: false } } });
  t.after(async () => { await app.close(); await pool.end(); await admin.query(`DROP SCHEMA ${schema} CASCADE`); await admin.end(); });
  await pool.query('CREATE TABLE users(id uuid PRIMARY KEY)');
  await pool.query(await readFile(new URL('../../apps/api/migrations/0160_learning_practice.sql', import.meta.url), 'utf8'));
  const userId = randomUUID(), otherId = randomUUID();
  await pool.query('INSERT INTO users VALUES($1),($2)', [userId, otherId]);
  const actor = { userId }, repository = new PostgresPracticeRepository(pool), engine = createVerifiedMathEngine();
  const service = createPracticeService({ repository, engine });
  const worker = createPracticeWorker({ repository, engine });
  app.setErrorHandler((error, _request, reply) => reply.code(error.statusCode || 500).send({ error: { code: error.code, message: error.message } }));
  registerPracticeRoutes(app, { service, requireAuth: async request => {
    if (request.headers.authorization !== 'Bearer local-acceptance') throw new PracticeError('AUTH_REQUIRED', 401, 'Sign in');
    request.actor = actor;
  } });
  const config = { subjectId: 'mathematics', curriculumId: 'csca-math-1.43', topicId: 'csca.math.sets', difficultyId: 'basic', count: 3, language: 'en' };
  assert.equal((await app.inject({ url: '/v1/me/practice' })).statusCode, 401);
  const request = input => app.inject({ ...input, headers: { authorization: 'Bearer local-acceptance', ...input.headers } });
  const start = await request({ method: 'POST', url: '/v1/me/practice', headers: { 'idempotency-key': 'acceptance-first' }, payload: config });
  assert.equal(start.statusCode, 200, start.body);
  let batch = start.json().data;
  assert.equal(batch.status, 'queued');
  const [same1, same2] = await Promise.all([service.start(actor, config, 'acceptance-first'), service.start(actor, config, 'acceptance-first')]);
  assert.equal(same1.id, batch.id); assert.equal(same2.id, batch.id);
  await assert.rejects(service.start(actor, { ...config, count: 5 }, 'acceptance-first'), { code: 'PRACTICE_KEY_CONFLICT' });
  assert.equal(await worker.runOnce(), true);
  batch = await service.get(actor, batch.id);
  assert.equal(batch.status, 'ready', JSON.stringify(batch)); assert.equal(batch.items.length, 3);
  assert.doesNotMatch(JSON.stringify(batch), /correctAnswer|explanation|evidence|identityHash|localizations|generationSource/);
  await assert.rejects(service.get({ userId: otherId }, batch.id), { code: 'PRACTICE_NOT_FOUND' });
  const privateBatch = await repository.get(userId, batch.id);
  const first = privateBatch.items[0].question;
  batch = await service.update(actor, batch.id, { action: 'save', expectedRevision: batch.revision, questionId: first.id, answer: first.correctAnswer, currentIndex: 1, elapsedSeconds: 12 });
  // A new service instance represents process/browser recovery; state comes from PG.
  const restoredService = createPracticeService({ repository: new PostgresPracticeRepository(pool), engine });
  let restored = await restoredService.get(actor, batch.id);
  assert.equal(restored.items[0].answer, first.correctAnswer); assert.equal(restored.currentIndex, 1);
  await assert.rejects(service.update(actor, batch.id, { action: 'save', expectedRevision: 1, questionId: first.id, answer: 'A' }), { code: 'PRACTICE_REVISION_CONFLICT' });
  batch = await service.update(actor, batch.id, { action: 'check', expectedRevision: restored.revision, questionId: first.id });
  assert.equal(batch.items[0].correct, true); assert.equal(batch.items[0].explanation, first.localizations.en.explanation);
  assert.equal('correctAnswer' in batch.items[1], false);
  await assert.rejects(service.update(actor, batch.id, { action: 'save', expectedRevision: batch.revision, questionId: first.id, answer: first.options.find(o => o.id !== first.correctAnswer).id }), { code: 'PRACTICE_ANSWER_LOCKED' });
  await assert.rejects(service.continue(actor, batch.id, 'before-complete'), { code: 'PRACTICE_NOT_COMPLETED' });
  batch = await service.update(actor, batch.id, { action: 'submit', expectedRevision: batch.revision });
  assert.equal(batch.correct, 1); assert.equal(batch.total, 3);
  const again = await service.update(actor, batch.id, { action: 'submit', expectedRevision: 1 });
  assert.equal(again.revision, batch.revision);
  await assert.rejects(service.continue(actor, batch.id, 'acceptance-first'), { code: 'PRACTICE_KEY_CONFLICT' });
  const history = await service.history(actor); assert.equal(history.topics[0].attempted, 3); assert.equal(history.topics[0].correct, 1); assert.equal(history.wrong.length, 2);
  const [next, repeated] = await Promise.all([service.continue(actor, batch.id, 'next:' + batch.id), service.continue(actor, batch.id, 'other-next-key')]);
  assert.equal(next.id, repeated.id); assert.deepEqual(next.config, batch.config);
  await worker.runOnce();
  const successor = await repository.get(userId, next.id);
  assert.equal(successor.status, 'ready');
  assert.equal(successor.items.some(i => privateBatch.items.some(old => old.question.identityKey === i.question.identityKey)), false);
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM practice_exposures WHERE user_id=$1', [userId])).rows[0].n, 6);
  // Simulate a crashed worker; a replacement reclaims the expired durable task.
  const recovering = await service.start(actor, { ...config, difficultyId: 'medium' }, 'recover-task-001');
  const claimed = await repository.claim(); assert.equal(claimed.id, recovering.id);
  await pool.query("UPDATE practice_batches SET lease_until=now()-interval '1 second' WHERE id=$1", [claimed.id]);
  const replacement = await repository.claim(); assert.equal(replacement.id, recovering.id); assert.notEqual(replacement.leaseToken, claimed.leaseToken);
  assert.equal(await repository.publish(claimed, []), false);
  await repository.fail(replacement, 'PRACTICE_PREPARATION_FAILED');
  const retry = await service.retry(actor, recovering.id); assert.equal(retry.status, 'queued');
  const retriedClaim = await repository.claim(); assert.equal(retriedClaim.attempts, 1);
  await service.start(actor, config, 'quota-first-001');
  await repository.fail(retriedClaim, 'PRACTICE_PREPARATION_FAILED');
  await service.start(actor, config, 'quota-second-001');
  await assert.rejects(service.retry(actor, recovering.id), { code: 'PRACTICE_BUSY' });
  // Invalid browser-owned identities/config never reach the service.
  const invalid = await request({ method: 'POST', url: '/v1/me/practice', payload: { ...config, userId: otherId }, headers: { 'idempotency-key': 'bad-owner-001' } });
  assert.equal(invalid.statusCode, 400);
  await worker.stop();
});
