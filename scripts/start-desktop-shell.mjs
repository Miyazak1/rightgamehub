import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { createReadStream } from 'node:fs';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const { desktopAccountLaunchOptions, prepareDesktopAccountProfile } = await import('../apps/desktop/src/account-configuration.mjs');
const { accountApiOrigin, accountEnvironment, profileRoot, dedicatedConfig } = desktopAccountLaunchOptions(process.argv.slice(2), root);
const runtimeRoot = path.resolve(root, '../../.runtime/electron-v44.4.5-win32-x64');
const executable = path.join(runtimeRoot, 'electron.exe');
const expected = 'bd14928e0728366fd3f41499cb398ff3f4304dab259a3e605077899a6f8c748e';
const hash = crypto.createHash('sha256'); for await (const chunk of createReadStream(executable)) hash.update(chunk);
if (hash.digest('hex') !== expected) throw Error('DESKTOP_DEVELOPMENT_RUNTIME_HASH_MISMATCH');
const assets = path.join(root, '.runtime/desktop-shell/web');
await fs.access(path.join(assets, 'index.html'));
const config = dedicatedConfig ? path.join(profileRoot, 'launch.json') : path.join(root, '.runtime/desktop-shell/launch.json');
await prepareDesktopAccountProfile(profileRoot, accountApiOrigin, accountEnvironment);
await fs.mkdir(profileRoot, { recursive: true });
await fs.writeFile(config, JSON.stringify({ assetRoot: assets, profileRoot, accountApiOrigin, accountEnvironment, initialRoute: accountApiOrigin ? '/account' : '/discover', electronExecutable: executable, electronEntry: path.join(root, 'apps/desktop/electron/main.cjs') }, null, 2));
const environment = { ...process.env }; delete environment.ELECTRON_RUN_AS_NODE;
const child = spawn(executable, [path.join(root, 'apps/desktop/electron/main.cjs'), '--config', config], { cwd: root, env: environment, windowsHide: false, stdio: ['ignore', 'pipe', 'pipe'] });
child.stdout.pipe(process.stdout); child.stderr.pipe(process.stderr);
child.on('error', () => { process.stderr.write('DESKTOP_LAUNCH_FAILED\n'); process.exitCode = 70; });
child.on('exit', code => { process.exitCode = code ?? 70; });
